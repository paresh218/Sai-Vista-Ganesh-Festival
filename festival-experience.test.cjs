const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const context={Intl,Date,window:{},module:{exports:{}},FestivalRegistration:require('./event-registration-model.js')};
vm.createContext(context);
vm.runInContext(fs.readFileSync('site-data.js','utf8'),context);
vm.runInContext(fs.readFileSync('festival-experience.js','utf8'),context);
const E=context.module.exports,events=context.window.SaiVistaContent.festivalEvents;
assert.equal(E.dayKey(new Date('2026-09-17T18:30:00Z')),'2026-09-18');
assert.equal(E.agenda(events,new Date('2026-09-17T10:00:00Z')).today.date,'2026-09-17');
assert.equal(E.agenda(events,new Date('2026-09-17T10:00:00Z')).next.date,'2026-09-18');
assert.equal(E.agenda(events,new Date('2027-09-17')).today,undefined);
assert.equal(E.agenda(events,new Date('2026-09-26')).next,undefined);
assert.equal(E.agenda(events,new Date('2026-09-06')).next.date,'2026-09-14');
assert.equal(E.badge('fancy',new Date('2026-09-17T18:29:59Z')).label,'Closing today');
assert.equal(E.badge('fancy',new Date('2026-09-17T18:30:00Z')).label,'Closed');
assert.equal(E.badge('bollywood',new Date('2026-09-17T10:00:00Z')).label,'Open');
assert.equal(E.badge('talent',new Date('2026-09-17T10:00:00Z')).label,'Closed');
console.log('PASS: India date rollover, next scheduled day, festival year/end, and registration badge boundaries.');
