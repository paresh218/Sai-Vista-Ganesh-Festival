import { act, fireEvent, render, screen } from '@testing-library/react';
import type { Firestore } from 'firebase/firestore';
import { beforeEach, expect, it, vi } from 'vitest';
import { InvitationPanel } from '../web/src/features/invitations/InvitationPanel';
import { InvitationError } from '../web/src/features/invitations/data';
const mock = vi.hoisted(() => ({ create: vi.fn(), accept: vi.fn(), cancel: vi.fn() }));
vi.mock('../web/src/features/invitations/data', async importOriginal => ({ ...await importOriginal<object>(), createInvitation: (...args: unknown[]) => mock.create(...args), acceptInvitation: (...args: unknown[]) => mock.accept(...args), cancelInvitation: (...args: unknown[]) => mock.cancel(...args) }));
vi.mock('../web/src/features/platform/RecordBrowser', () => ({ RecordBrowser: ({ onSelect }: { onSelect: (id: string) => void }) => <button onClick={() => onSelect('existing-code')}>Open invitation history record</button> }));
const props = { database: {} as Firestore, societyId: 'alpha', uid: 'owner', email: 'owner@example.test' };
beforeEach(() => { vi.clearAllMocks(); mock.create.mockResolvedValue('new-code'); mock.accept.mockResolvedValue(undefined); mock.cancel.mockResolvedValue(undefined); });
it('owner creates invitations, sees code only after confirmation, selects history and cancels', async () => {
  render(<InvitationPanel {...props} owner />);
  fireEvent.change(screen.getByLabelText('Recipient email'), { target: { value: 'guest@example.test' } });
  fireEvent.change(screen.getByLabelText('Invitation access'), { target: { value: 'admin' } });
  fireEvent.click(screen.getByRole('button', { name: 'Create invitation' }));
  await screen.findByText('new-code');
  expect(mock.create).toHaveBeenCalledWith(props.database, 'alpha', 'owner', 'guest@example.test', 'admin');
  fireEvent.click(screen.getByRole('button', { name: 'Open invitation history record' }));
  fireEvent.click(screen.getByRole('button', { name: 'Cancel invitation' }));
  await screen.findByText('Invitation cancelled. It can no longer be accepted.');
  expect(mock.cancel).toHaveBeenCalledWith(props.database, 'alpha', 'existing-code');
});
it('recipient submits code once while busy and gets success only after acceptance', async () => {
  let finish!: () => void;
  mock.accept.mockImplementationOnce(() => new Promise<void>(resolve => { finish = resolve; }));
  render(<InvitationPanel {...props} owner={false} />);
  expect(screen.queryByLabelText('Recipient email')).toBeNull();
  fireEvent.change(screen.getByLabelText('Invitation code'), { target: { value: 'code' } });
  fireEvent.click(screen.getByRole('button', { name: 'Accept invitation' }));
  fireEvent.click(screen.getByRole('button', { name: 'Accept invitation' }));
  expect(mock.accept).toHaveBeenCalledOnce();
  expect(screen.queryByText('Invitation accepted. Membership is now active in this community.')).toBeNull();
  await act(async () => finish());
  await screen.findByText('Invitation accepted. Membership is now active in this community.');
  expect(mock.accept).toHaveBeenCalledWith(props.database, 'alpha', { uid: 'owner', email: props.email }, 'code');
  expect((screen.getByLabelText('Invitation code') as HTMLInputElement).value).toBe('');
});
it('failed creation or acceptance retains input and never claims success', async () => {
  mock.create.mockRejectedValueOnce(new Error('offline'));
  const view = render(<InvitationPanel {...props} owner />);
  fireEvent.change(screen.getByLabelText('Recipient email'), { target: { value: 'guest@example.test' } });
  fireEvent.click(screen.getByRole('button', { name: 'Create invitation' }));
  await screen.findByText('Invitation could not be updated. Check your account, community, code and connection.');
  expect((screen.getByLabelText('Recipient email') as HTMLInputElement).value).toBe('guest@example.test');
  expect(screen.queryByText('new-code')).toBeNull();
  view.unmount();
  mock.accept.mockRejectedValueOnce(new Error('denied'));
  render(<InvitationPanel {...props} owner={false} />);
  fireEvent.change(screen.getByLabelText('Invitation code'), { target: { value: 'wrong-code' } });
  fireEvent.click(screen.getByRole('button', { name: 'Accept invitation' }));
  await screen.findByText('Invitation could not be updated. Check your account, community, code and connection.');
  expect((screen.getByLabelText('Invitation code') as HTMLInputElement).value).toBe('wrong-code');
});
it('failed cancellation retains its code and actionable validation errors are shown', async () => {
  mock.cancel.mockRejectedValueOnce(new InvitationError('Enter a valid invitation code.'));
  render(<InvitationPanel {...props} owner />);
  fireEvent.change(screen.getByLabelText('Code to cancel'), { target: { value: 'bad/code' } });
  fireEvent.click(screen.getByRole('button', { name: 'Cancel invitation' }));
  await screen.findByText('Enter a valid invitation code.');
  expect((screen.getByLabelText('Code to cancel') as HTMLInputElement).value).toBe('bad/code');
  expect(screen.queryByText('Invitation cancelled. It can no longer be accepted.')).toBeNull();
});
